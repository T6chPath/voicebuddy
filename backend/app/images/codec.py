"""Decode untrusted images safely and encode results in the requested format."""
from __future__ import annotations

import io

from PIL import Image, ImageOps, PngImagePlugin

MAX_INPUT_PIXELS = 40_000_000          # refuse decompression bombs before decoding
MAX_WORK_SIDE = 2048                   # inputs are scaled down to this before processing
Image.MAX_IMAGE_PIXELS = MAX_INPUT_PIXELS
MIME = {"png": "image/png", "jpeg": "image/jpeg", "webp": "image/webp"}


class BadImage(ValueError):
    pass


def load(data: bytes, mode: str = "RGB") -> Image.Image:
    try:
        with Image.open(io.BytesIO(data)) as probe:
            if probe.width * probe.height > MAX_INPUT_PIXELS:
                raise BadImage("The image is too large (over 40 megapixels).")
            probe.verify()
        im = Image.open(io.BytesIO(data))
        im.seek(0)                                   # first frame of GIF/animated WebP
        im = ImageOps.exif_transpose(im)
        im.load()
    except BadImage:
        raise
    except (Image.DecompressionBombError, OSError, SyntaxError, ValueError) as e:
        raise BadImage("That file couldn't be read as an image.") from e
    if mode == "RGB" and im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGBA")
        bg = Image.new("RGB", im.size, (255, 255, 255))
        bg.paste(im, mask=im.split()[-1])
        im = bg
    elif im.mode != mode:
        im = im.convert(mode)
    if max(im.size) > MAX_WORK_SIDE:
        im.thumbnail((MAX_WORK_SIDE, MAX_WORK_SIDE), Image.LANCZOS)
    return im


def load_mask(data: bytes, size: tuple[int, int]) -> Image.Image:
    """Mask → 'L' image the size of the source: 255 = change, 0 = keep.
    Accepts white-on-black masks and transparent-hole masks (transparent = change, the OpenAI convention)."""
    im = load(data, mode="RGBA")
    alpha = im.split()[-1]
    if alpha.getextrema()[0] < 250:                  # has transparency → transparent means "edit here"
        m = ImageOps.invert(alpha)
    else:
        m = im.convert("L")
    m = m.resize(size, Image.NEAREST).point(lambda v: 255 if v >= 128 else 0)
    if m.getbbox() is None:
        raise BadImage("The mask is empty — paint over the area you want to change.")
    return m


def encode(im: Image.Image, fmt: str, *, provider: str, model: str) -> tuple[bytes, str, list[str]]:
    """Re-encode (drops any metadata the provider attached) and label the file as AI-generated."""
    notes: list[str] = []
    fmt = fmt if fmt in MIME else "png"
    if fmt == "jpeg" and im.mode in ("RGBA", "LA"):
        bg = Image.new("RGB", im.size, (255, 255, 255))
        bg.paste(im, mask=im.split()[-1])
        im = bg
        notes.append("JPEG has no transparency, so the background was filled with white.")
    elif im.mode not in ("RGB", "RGBA"):
        im = im.convert("RGBA" if "A" in im.mode else "RGB")
    out = io.BytesIO()
    label = f"AI-generated by zenvqo ({provider}: {model})"
    if fmt == "png":
        info = PngImagePlugin.PngInfo()
        info.add_text("Software", "zenvqo")
        info.add_text("Comment", label)
        im.save(out, "PNG", pnginfo=info, optimize=True)
    elif fmt == "webp":
        im.save(out, "WEBP", quality=92, method=4)
    else:
        im.save(out, "JPEG", quality=92, optimize=True, progressive=True, comment=label.encode())
    return out.getvalue(), MIME[fmt], notes
